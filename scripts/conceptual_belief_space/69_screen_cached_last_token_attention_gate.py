#!/usr/bin/env python3
"""Screen tiny last-token score-query gates on cached nested OOF evidence.

This is a development-only utility.  It reuses source evidence generated by
``68_train_nested_last_token_attention_probe.py`` so gate objectives and
learning rates can be compared without retraining the activation experts.
Selection is based on the gate's grouped meta-validation trajectories, not on
the outer development-test labels.
"""

from __future__ import annotations

import argparse
import copy
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

NESTED_SCRIPT = Path(__file__).with_name("68_train_nested_last_token_attention_probe.py")
spec = importlib.util.spec_from_file_location("cached_last_token_gate_nested_impl", NESTED_SCRIPT)
nested = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = nested
assert spec and spec.loader
spec.loader.exec_module(nested)

base = nested.base
fixed = nested.fixed
seg = nested.seg
ACTIONS = nested.ACTIONS
Q_COLS = nested.Q_COLS


def parse_floats(text: str) -> list[float]:
    return [float(value.strip()) for value in text.split(",") if value.strip()]


def parse_strings(text: str) -> list[str]:
    return [value.strip() for value in text.split(",") if value.strip()]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence_dir", required=True)
    parser.add_argument("--output_dir", default="outputs/conceptual_belief_space/cached_last_token_attention_gate_screen")
    parser.add_argument("--beliefs", default="outputs/conceptual_belief_space/action_belief_vectors_mlx_full.parquet")
    parser.add_argument("--prefixes", default="outputs/prefixes.parquet")
    parser.add_argument("--split_id", type=int, default=0)
    parser.add_argument("--n_splits", type=int, default=5)
    parser.add_argument("--gate_losses", default="balanced_ce,ovr_bce")
    parser.add_argument("--gate_lrs", default="0.00005,0.0001,0.0005")
    parser.add_argument("--rank_weights", default="0,0.1")
    parser.add_argument("--gate_epochs", type=int, default=30)
    parser.add_argument("--gate_patience", type=int, default=6)
    parser.add_argument("--meta_val_fraction", type=float, default=0.15)
    parser.add_argument("--attention_dim", type=int, default=4)
    parser.add_argument("--dropout", type=float, default=0.0)
    parser.add_argument("--q_soft_loss_weight", type=float, default=0.0)
    parser.add_argument("--weight_decay", type=float, default=1e-3)
    parser.add_argument("--grad_clip", type=float, default=5.0)
    parser.add_argument("--min_delta", type=float, default=1e-4)
    parser.add_argument("--batch_size", type=int, default=256)
    parser.add_argument("--gate_batch_size", type=int, default=512)
    parser.add_argument("--eval_batch_size", type=int, default=1024)
    parser.add_argument("--seed", type=int, default=base.DEFAULT_SEED)
    return parser.parse_args()


def main() -> int:
    import torch

    args = parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    evidence_dir = Path(args.evidence_dir)
    oof_path = evidence_dir / f"nested_last_token_attention_oof_evidence_split_{args.split_id}.npz"
    test_path = evidence_dir / f"nested_last_token_attention_test_evidence_split_{args.split_id}.npz"
    if not oof_path.exists() or not test_path.exists():
        raise FileNotFoundError(f"Missing cached evidence: {oof_path} or {test_path}")

    df = fixed.rank_impl.prepare_belief_rows(
        Path(args.beliefs),
        limit_decisions=None,
        seed=args.seed,
        prefix_path=Path(args.prefixes),
    ).reset_index(drop=True)
    y = base.action_indices(df["top_action"])
    q_all = df[Q_COLS].to_numpy(dtype=np.float32)
    splits = fixed.rank_impl.make_group_splits(df, args.n_splits, args.seed)
    split = next(item for item in splits if int(item["split_id"]) == args.split_id)
    outer_train = np.asarray(split["train_idx"], dtype=np.int64)
    test_idx = np.asarray(split["test_idx"], dtype=np.int64)
    base.assert_group_disjoint(df, outer_train, test_idx, f"cached split {args.split_id}")

    with np.load(oof_path) as data:
        cached_outer = data["row_indices"].astype(np.int64)
        cached_oof = data["source_evidence"].astype(np.float32)
    with np.load(test_path) as data:
        cached_test = data["row_indices"].astype(np.int64)
        test_evidence = data["source_evidence"].astype(np.float32)
    if not np.array_equal(cached_outer, outer_train):
        raise RuntimeError("Cached OOF row order does not match the canonical outer split")
    if not np.array_equal(cached_test, test_idx):
        raise RuntimeError("Cached test row order does not match the canonical outer split")
    oof_evidence = np.full(
        (len(df), len(nested.SOURCE_NAMES), len(ACTIONS)), np.nan, dtype=np.float32
    )
    oof_evidence[outer_train] = cached_oof

    # These are deliberately unused for last1_scores query mode.
    arrays: dict = {}
    layers: list[int] = []
    feature_rows = np.zeros(len(df), dtype=np.int64)
    pre_rows = np.zeros(len(df), dtype=np.int64)
    metric_rows: list[dict] = []
    candidate_rows: list[dict] = []
    histories: list[pd.DataFrame] = []
    state_by_config: dict[str, dict] = {}

    for loss_kind in parse_strings(args.gate_losses):
        for gate_lr in parse_floats(args.gate_lrs):
            for rank_weight in parse_floats(args.rank_weights):
                config_name = (
                    f"{loss_kind}_lr{gate_lr:g}_rank{rank_weight:g}".replace(".", "p")
                )
                run_args = copy.copy(args)
                run_args.query_mode = "last1_scores"
                run_args.gate_loss = loss_kind
                run_args.gate_lr = gate_lr
                run_args.q_rank_loss_weight = rank_weight
                print(f"Config {config_name}", flush=True)
                gate, query_scaler, device, history, info, state = nested.train_attention_gate(
                    oof_evidence,
                    outer_train,
                    arrays,
                    layers,
                    df,
                    y,
                    q_all,
                    feature_rows,
                    pre_rows,
                    run_args,
                    args.split_id,
                )
                assert query_scaler is None
                rng = np.random.default_rng(args.seed + 200_000 + args.split_id)
                shuffled = test_idx.copy()
                rng.shuffle(shuffled)
                outputs = nested.predict_gate(
                    gate,
                    test_evidence,
                    test_idx,
                    arrays,
                    layers,
                    feature_rows,
                    pre_rows,
                    None,
                    args.eval_batch_size,
                    device,
                    query_mode="last1_scores",
                    shuffled_query_indices=shuffled,
                )
                start = len(metric_rows)
                base.add_all_metrics(
                    metric_rows,
                    df,
                    test_idx,
                    outputs,
                    args.split_id,
                    info,
                )
                for row in metric_rows[start:]:
                    row["config_name"] = config_name
                    row["gate_loss"] = loss_kind
                    row["gate_lr"] = gate_lr
                    row["rank_weight"] = rank_weight
                    row["development_only"] = True
                candidate_rows.append(
                    {
                        "config_name": config_name,
                        "gate_loss": loss_kind,
                        "gate_lr": gate_lr,
                        "rank_weight": rank_weight,
                        **info,
                    }
                )
                history_df = pd.DataFrame(history)
                history_df.insert(0, "config_name", config_name)
                histories.append(history_df)
                state_by_config[config_name] = state

    candidates = pd.DataFrame(candidate_rows).sort_values(
        ["gate_validation_balanced_accuracy", "best_gate_epoch"],
        ascending=[False, True],
    )
    selected_name = str(candidates.iloc[0]["config_name"])
    candidates["selected_by_meta_validation"] = candidates["config_name"].eq(selected_name)
    metrics = pd.DataFrame(metric_rows)
    metrics["selected_by_meta_validation"] = metrics["config_name"].eq(selected_name)
    candidates.to_csv(output_dir / "cached_gate_candidates.csv", index=False)
    metrics.to_csv(output_dir / "cached_gate_metrics.csv", index=False)
    pd.concat(histories, ignore_index=True).to_csv(output_dir / "cached_gate_history.csv", index=False)
    torch.save(
        {
            "selected_config": candidates.iloc[0].to_dict(),
            "gate_state_dict": state_by_config[selected_name],
            "source_names": nested.SOURCE_NAMES,
            "actions": list(ACTIONS),
            "query_mode": "last1_scores",
            "evidence_dir": str(evidence_dir),
            "development_split": int(args.split_id),
        },
        output_dir / "selected_cached_last_token_attention_gate.pt",
    )
    selected_metrics = metrics[
        metrics["selected_by_meta_validation"]
        & metrics["eval_subset"].eq("all_prefixes")
    ][
        ["source_name", "balanced_accuracy", "accuracy", "macro_f1", "pairwise_accuracy"]
    ]
    report = [
        "# Cached Last-Token Score-Query Gate Screen",
        "",
        "Development-only screen; configuration selection uses grouped gate meta-validation.",
        "",
        "## Selected configuration",
        "",
        candidates.head(1).to_markdown(index=False),
        "",
        "## Outer development-fold diagnostics",
        "",
        selected_metrics.to_markdown(index=False),
    ]
    (output_dir / "cached_gate_report.md").write_text("\n".join(report) + "\n")
    (output_dir / "cached_gate_manifest.json").write_text(
        json.dumps(
            {
                "development_only": True,
                "selection_metric": "grouped meta-validation balanced accuracy",
                "selected_config": selected_name,
                "query": "four action-evidence scores decoded from the actual last prefix token",
                "forbidden_inputs": base.FORBIDDEN_MODEL_INPUTS,
                "arguments": vars(args),
            },
            indent=2,
        )
        + "\n"
    )
    print(candidates.to_string(index=False), flush=True)
    print(selected_metrics.to_string(index=False), flush=True)
    print(f"Selected {selected_name}; wrote {output_dir}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
